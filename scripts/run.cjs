"use strict";
const path = require("node:path");
const { spawn } = require("node:child_process");
const env = { ...process.env };
delete env.ELECTRON_RUN_AS_NODE;
const args = process.argv.slice(2);
const hostTest = args.includes("--host-test");
const visibilityTest = args.includes("--visibility-test");
const resumeTest = args.includes("--resume-test");
const appearanceTest = args.includes("--appearance-test");
const concurrencyTest = args.includes("--concurrency-test");
const packagedCode = args.includes("--packaged-code");
if (packagedCode) env.DESKWEEK_APP_ROOT = path.resolve(__dirname, "..", process.env.DESKWEEK_BUILD_DIR || "dist", "DeskWeek-win32-x64/resources/app.asar");
const testFile = concurrencyTest ? "concurrency.electron.cjs" : appearanceTest ? "appearance.electron.cjs" : resumeTest ? "resume.electron.cjs" : visibilityTest ? "visibility.electron.cjs" : hostTest ? "host.electron.cjs" : null;
const child = spawn(require("electron"), testFile ? [path.resolve(__dirname, "../test", testFile)] : [path.resolve(__dirname, ".."), ...args], { env, stdio: "inherit" });
child.once("error", error => { console.error(error); process.exitCode = 1; });
child.once("exit", code => { process.exitCode = code ?? 1; });
